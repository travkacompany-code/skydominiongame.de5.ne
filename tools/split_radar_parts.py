os.makedirs("assets/sprites/radar_parts", exist_ok=True)
meta = {}
for rid, (rects, pv) in PARTS.items():
    im = Image.open(f"assets/sprites/radar/{rid}.png").convert("RGBA"); a = np.array(im)
    m = np.zeros(a.shape[:2], bool)
    for (x0, y0, x1, y1) in rects: m[y0:y1, x0:x1] = True
    ant = a.copy(); ant[~(m & (a[..., 3] > 0))] = 0
    body = a.copy(); body[m] = 0
    ys, xs = np.where(ant[..., 3] > 0)
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    Image.fromarray(ant[y0:y1, x0:x1]).save(f"assets/sprites/radar_parts/{rid}_ant.png")
    Image.fromarray(body).save(f"assets/sprites/radar_parts/{rid}_body.png")
    meta[rid] = {"W": im.size[0], "H": im.size[1], "ax": int(x0), "ay": int(y0), "px": pv[0], "py": pv[1]}
json.dump(meta, open("assets/sprites/radar_parts/parts.json", "w"), indent=1)
print(len(meta), "спрайтів розділено")
